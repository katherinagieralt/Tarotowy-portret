function reduceTo22(num: number): number {
  while (num <= 0) {
    num += 22;
  }
  while (num > 22) {
    num -= 22;
  }
  return num;
}

function sumYear(year: number): number {
  return year
    .toString()
    .split("")
    .reduce((acc, digit) => acc + Number(digit), 0);
}

function diff(a: number, b: number): number {
  const result = Math.abs(a - b);
  return result === 0 ? 22 : result;
}

