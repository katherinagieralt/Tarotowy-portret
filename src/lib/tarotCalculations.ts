export function calculatePartnershipPortrait(
  date1: Date | string,
  date2: Date | string,
  locale: "pl" | "en" = "pl"
) {
  const personA = calculateIndividualPortrait(date1, locale);
  const personB = calculateIndividualPortrait(date2, locale);

  const p1 = reduceTo22(personA.points.p1 + personB.points.p1);
  const p2 = reduceTo22(personA.points.p2 + personB.points.p2);
  const p3 = reduceTo22(personA.points.p3 + personB.points.p3);
  const p4 = reduceTo22(personA.points.p4 + personB.points.p4);
  const p5 = reduceTo22(personA.points.p5 + personB.points.p5);
  const p6 = reduceTo22(personA.points.p6 + personB.points.p6);
  const p7 = reduceTo22(personA.points.p7 + personB.points.p7);
  const p8 = reduceTo22(personA.points.p8 + personB.points.p8);

  const combinedPoints = { p1, p2, p3, p4, p5, p6, p7, p8 };

  const positionMeanings = locale === "en" ? partnerPositionMeaningsEn : partnerPositionMeanings;

  const mapPoint = (val: number, posKey: string) => ({
    number: val,
    name: locale === "en" ? ARCANA_EN[val] : ARCANA[val],
    description: locale === "en" ? ARCANA_DESCRIPTIONS_EN[val] : ARCANA_DESCRIPTIONS[val],
    positionMeaning: positionMeanings[posKey],
    posKey,
    slug: ARCANA_SLUGS[val]
  });

  return {
    person1: personA,
    person2: personB,
    combinedPoints,
    combined: {
      arcanaNumber: p6, // Główny cel relacji
      arcanaName: locale === "en" ? ARCANA_EN[p6] : ARCANA[p6],
      description: locale === "en" ? ARCANA_DESCRIPTIONS_EN[p6] : ARCANA_DESCRIPTIONS[p6],
    },
    detailedCards: {
      p1: mapPoint(p1, "p1"),
      p2: mapPoint(p2, "p2"),
      p3: mapPoint(p3, "p3"),
      p4: mapPoint(p4, "p4"),
      p5: mapPoint(p5, "p5"),
      p6: mapPoint(p6, "p6"),
      p7: mapPoint(p7, "p7"),
      p8: mapPoint(p8, "p8"),
    }
  };
}

